hasil = ""

for report in data:
    modifier = int(report[0:2], 16)
    keycode = int(report[4:6], 16)

    if keycode == 0:
        continue

    karakter = hid_keycodes.get(keycode, '?')

    if modifier == 0x02:
        karakter = karakter.upper() if karakter.isalpha() else {
            '-': '_'
        }.get(karakter, karakter)

    hasil += karakter

print(hasil)